function getInstitutions(daaira, baladiya, level) {
  if (level === "ابتدائي") {
    return (primarySchoolsByBaladiya[baladiya] || []).map(s => s.name);
  } else if (level === "متوسط" || level === "ثانوي") {
    if (institutionsByDaaira[daaira] && institutionsByDaaira[daaira][level]) {
      return institutionsByDaaira[daaira][level].map(s => s.name);
    }
  }
  return [];
}
